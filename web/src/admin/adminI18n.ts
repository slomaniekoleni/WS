/** Admin panel strings, following the site's EN/RU switch. */
export function useAdminT() {
  const { lang } = useI18n()
  // Stable per language, so it can sit in effect dependencies.
  return useCallback(
    (key: AdminKey, vars?: Record<string, string | number>) =>
      (lang === 'ru' ? ru : en)[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? '')),
    [lang],
  )
}
